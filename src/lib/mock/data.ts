// Helper — days from today in ISO form.
function daysFromToday(days: number, hour = 9, minute = 15): string {
  // Anchor to the session's "today" (2026-04-16) so the demo stays coherent
  // regardless of when it is executed.
  const today = new Date("2026-04-16T00:00:00Z");
  const d = new Date(today);
  d.setUTCDate(d.getUTCDate() + days);
  d.setUTCHours(hour, minute, 0, 0);
  return d.toISOString();
}

function iso(offsetDays: number): string {
  return daysFromToday(offsetDays).slice(0, 10);
}

